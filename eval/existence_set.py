# -*- coding: utf-8 -*-
"""存在性/可回答性问题集：度量"证据没回答问题却照样作答"的假阳性率。

为什么需要这个集
----------------
线上真实案例：「车内有冰箱吗」→ 系统拿第 129 页"12V 电源可以给车载冰箱充电"作答。
检索没错、接地没错，但**没回答问题**。这类问题之前**没有任何指标覆盖**，
所以回归时永远发现不了。

集子怎么设计的
--------------
三类期望，覆盖"该限定 / 该正常答 / 该拒答"：

| expect | 含义 | 期望 status |
| --- | --- | --- |
| `limited` | **检索到了**它（举例/受电/警示/选装语境），但没说明配备 | `limited` |
| `answered` | 手册里有明确配置或操作说明 | `answered` |
| `refused` | **检索不到**相关内容 | `refused` |

> `limited` 与 `refused` 的分界线是**有没有检索到相关内容**，不是"手册有没有写"：
> 提到了但语境不支持 → 限定（告诉用户手册怎么说的）；压根没提到 → 拒答。

关键指标
--------
- **假阳性率（FP）**：expect 是 `limited`/`refused`，系统却给了 `answered`
  → 这就是"用户问有没有冰箱，它甩一段给冰箱充电的原文"。
- **正确限定率**：expect `limited` 且 status `limited`。
- **过度限定率**：expect `answered` 却给了 `limited`（把该答的也限定了，同样是错）。

⚠️ 局限（如实说明）：判定用本项目自带语料（领克 08 手册），
结论只对这份语料成立；换车型手册需要重新标注这一批。
"""

